// 和上游的区别：屏幕方向可选（默认竖屏）、触摸和摄像头跟着屏幕方向转、
// 屏幕布局用 MercuryDisplay、增加电池电量检测、触摸互动用 MercuryTouch（见 mercury_touch.h）、
// 养成（配饰、心情温度）用 MercuryGrowth（见 mercury_growth.h）。
